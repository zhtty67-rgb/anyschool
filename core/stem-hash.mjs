// 题干指纹 —— 全项目唯一实现
//
// 为什么独立成一个模块（2026-11-05）：
//   之前有 4 份副本，而且都用"去标点后再算"的规则。Qbank 的标注文件用的是 md5(原文)。
//   两边算法不同 → 88 条标注一条都对不上 v10，白跑一轮。
//
// 为什么必须是 md5(原文)，不能先去掉标点：
//   这个函数的用途是校验"是不是同一道题"。去掉标点后，
//   「过拟合在训练集上准确率高」和「过拟合在训练集上准确率很高。」
//   会被算成同一道题——而这恰恰是最该被识别出来的"题干被改过"。
//   只有对原文算，才能精确捕捉"一个字变了"。
//
// 任何地方需要题干指纹，都从这里 import，不要再复制一份。
import { createHash } from 'node:crypto';

export function stemHash(stem) {
  return createHash('md5').update(String(stem == null ? '' : stem), 'utf8').digest('hex').slice(0, 8);
}
