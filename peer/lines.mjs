/** 取某概念的候选语句；没有就返回空数组 */
export function linesFor(conceptCode) {
  return LINES[conceptCode] || [];
}

/** 统计：每个概念有多少条，各立场多少条 */
export function libraryStats() {
  const byConcept = {};
  const byPosition = { misconception: 0, ask: 0, example: 0 };
  for (const [code, lines] of Object.entries(LINES)) {
    byConcept[code] = lines.length;
    for (const l of lines) byPosition[l.position] += 1;
  }
  return { byConcept, byPosition, total: Object.values(byConcept).reduce((a, b) => a + b, 0) };
}
